/** Report formatting + CSV (Excel) and PDF export. */
import PDFDocument from "pdfkit";
import { businessTz } from "../../lib/dates";
import { registerPdfFonts } from "../../lib/pdf-fonts";
import { formatDateLabel } from "../../lib/dates";
import { formatINR } from "../billing/calc";
import { formatQty } from "../inventory/qty";
import type { Column, ReportDef, Row } from "./definitions";

export function formatCell(col: Column, v: Row[string], symbol = "₹"): string {
  if (v === null || v === undefined || v === "") return "";
  switch (col.type) {
    case "money":
      return formatINR(Number(v), symbol);
    case "qty":
      return formatQty(Number(v));
    case "percent":
      return `${v}%`;
    case "date":
      return /^\d{4}-\d{2}-\d{2}$/.test(String(v)) ? formatDateLabel(String(v)) : String(v);
    case "number":
      return Number(v).toLocaleString("en-IN");
    default:
      return String(v);
  }
}

/** Raw value for CSV: numbers stay numeric (rupees with 2 decimals) so Excel can sum them. */
function csvValue(col: Column, v: Row[string]): string {
  if (v === null || v === undefined) return "";
  if (col.type === "money") return (Number(v) / 100).toFixed(2);
  if (col.type === "qty") return String(Number(v) / 1000);
  return String(v);
}

/** Neutralise spreadsheet formula injection (=, +, -, @ at the start of text). */
export function csvEscape(s: string, numeric = false): string {
  let out = s;
  if (!numeric && /^[=+\-@\t\r]/.test(out)) out = `'${out}`;
  return /[",\n\r]/.test(out) ? `"${out.replace(/"/g, '""')}"` : out;
}

export function toCsv(def: ReportDef, rows: Row[], totals: Row | null): string {
  const numeric = (c: Column) => c.type === "money" || c.type === "number" || c.type === "qty" || c.type === "percent";
  const lines = [def.columns.map((c) => csvEscape(c.label)).join(",")];
  for (const r of [...rows, ...(totals ? [totals] : [])]) {
    lines.push(def.columns.map((c) => csvEscape(csvValue(c, r[c.key] ?? null), numeric(c) && typeof r[c.key] === "number")).join(","));
  }
  return "﻿" + lines.join("\r\n"); // BOM so Excel reads UTF-8 (₹, Malayalam names…)
}

export async function toPdf(def: ReportDef, rows: Row[], totals: Row | null, meta: { company: string; filters: string; generatedBy: string }): Promise<Buffer> {
  const doc = new PDFDocument({ size: "A4", layout: "landscape", margin: 32, info: { Title: def.title } });
  const F = registerPdfFonts(doc);
  const chunks: Buffer[] = [];
  doc.on("data", (c: Buffer) => chunks.push(c));
  const done = new Promise<Buffer>((r) => doc.on("end", () => r(Buffer.concat(chunks))));
  const W = doc.page.width - 64;
  const L = 32;
  const weights = def.columns.map((c) => (c.type === "text" ? 2 : 1.2));
  const sum = weights.reduce((a, b) => a + b, 0);
  const widths = weights.map((w) => (w / sum) * W);
  const right = (c: Column) => c.type !== "text" && c.type !== "date";

  const header = () => {
    doc.font(F.bold).fontSize(14).fillColor("#0f172a").text(def.title, L, 32);
    doc.font(F.regular).fontSize(8).fillColor("#64748b").text(`${meta.company} · ${meta.filters} · generated by ${meta.generatedBy}, ${new Date().toLocaleString("en-IN", { timeZone: businessTz() })}`, L, 50);
    let x = L;
    const y = 70;
    doc.rect(L, y - 4, W, 16).fill("#f1f5f9");
    doc.font(F.bold).fontSize(7.5).fillColor("#475569");
    def.columns.forEach((c, i) => {
      doc.text(c.label.toUpperCase(), x + 3, y, { width: widths[i] - 6, align: right(c) ? "right" : "left" });
      x += widths[i];
    });
    return y + 16;
  };
  let y = header();
  const drawRow = (r: Row, bold = false) => {
    let x = L;
    doc.font(bold ? F.bold : F.regular).fontSize(8).fillColor("#0f172a");
    const h = Math.max(...def.columns.map((c, i) => doc.heightOfString(formatCell(c, r[c.key] ?? null, F.currency), { width: widths[i] - 6 })));
    if (y + h > doc.page.height - 40) {
      doc.addPage();
      y = header();
    }
    def.columns.forEach((c, i) => {
      doc.text(formatCell(c, r[c.key] ?? null, F.currency), x + 3, y, { width: widths[i] - 6, align: right(c) ? "right" : "left" });
      x += widths[i];
    });
    y += h + 5;
    doc.moveTo(L, y - 2).lineTo(L + W, y - 2).strokeColor("#e2e8f0").lineWidth(0.5).stroke();
  };
  if (rows.length === 0) doc.font(F.regular).fontSize(10).fillColor("#64748b").text("No data for these filters.", L, y + 10);
  rows.forEach((r) => drawRow(r));
  if (totals) drawRow(totals, true);
  doc.end();
  return done;
}
